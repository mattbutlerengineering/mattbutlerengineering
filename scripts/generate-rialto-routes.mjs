#!/usr/bin/env node
/**
 * generate-rialto-routes.mjs — derives infrastructure/worker/rialto-routes.generated.js,
 * the list of pages the rialto-web SPA really serves, from the route inventory
 * (scripts/ui-quality/routes.mjs). The edge router answers any other HTML page
 * under /rialto/ with 404 (#10000), so the list must never be hand-edited.
 *
 * Routes are stored without the /rialto mount and without a leading slash
 * ("/" for home); `:param` segments match any single segment.
 *
 * Usage: node scripts/generate-rialto-routes.mjs [generate|check]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRepoIo, extractApp } from "./ui-quality/routes.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const RIALTO_ROUTES_PATH = "infrastructure/worker/rialto-routes.generated.js";

/** Sorted, unique app-relative route paths of every concrete page route. */
export function collectRialtoRoutes(rows) {
  const routes = rows
    .filter((row) => row.kind === "page" && !row.route.includes("*"))
    .map((row) => (row.route === "/" ? "/" : `/${row.route}`));
  return [...new Set(routes)].sort();
}

function renderRialtoRoutes(routes) {
  const items = routes.map((route) => `  ${JSON.stringify(route)},`);
  return [
    "// GENERATED by scripts/generate-rialto-routes.mjs — do not edit.",
    "// Pages of the rialto-web SPA (route inventory), relative to the /rialto mount.",
    "export const RIALTO_ROUTES = [",
    ...items,
    "];",
    "",
  ].join("\n");
}

export function buildRialtoRoutes(io) {
  return renderRialtoRoutes(collectRialtoRoutes(extractApp("rialto-web", io)));
}

function main(argv) {
  const mode = argv[0] ?? "generate";
  const out = resolve(ROOT, RIALTO_ROUTES_PATH);
  const next = buildRialtoRoutes(createRepoIo(ROOT));
  if (mode === "check") {
    if (readFileSync(out, "utf8") !== next) {
      console.error(
        `${RIALTO_ROUTES_PATH} is stale — run: node scripts/generate-rialto-routes.mjs`
      );
      return 1;
    }
    return 0;
  }
  if (mode !== "generate") {
    console.error("usage: generate-rialto-routes.mjs [generate|check]");
    return 2;
  }
  writeFileSync(out, next);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
