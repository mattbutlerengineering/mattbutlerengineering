// One classifier for "is this path a generated artifact?" (#9080).
//
// Before this module the answer was copied into classify-human-touch,
// collect-code-churn, check-large-files and lint-staged.config.js, each
// drifting from the others. The committed outputs of `pnpm regen` come from
// the regen manifest; only the patterns the manifest cannot know live here.
//
// NOT used by scripts/tier-escalation.mjs: the tier-classifier workflow loads
// that file alone from the base branch (`git show origin/<base>:<file>`), so
// it must stay import-free. Its own list is pinned by tier-escalation tests.

import { posix } from "node:path";
import { artifactPaths } from "../regen-manifest.mjs";

// Includes files regen merely stages (a package.json that is also hand-edited);
// callers that must not treat those as generated carve them out themselves.
const MANIFEST_OUTPUTS = new Set(artifactPaths());

/** Generated by tooling outside the regen manifest, matched by basename. */
const NON_MANIFEST_BASENAMES = new Set(["pnpm-lock.yaml"]);

const GENERATED_DIR_RE = /(?:^|\/)generated\//;

/** True for any path under a `generated/` directory segment (Prisma clients etc.). */
export function isGeneratedDirPath(filePath) {
  return GENERATED_DIR_RE.test(filePath);
}

/**
 * True when `filePath` (repo-relative, POSIX separators) is a generated artifact.
 * @param {string} filePath
 * @returns {boolean}
 */
export function isGeneratedArtifact(filePath) {
  return (
    MANIFEST_OUTPUTS.has(filePath) ||
    NON_MANIFEST_BASENAMES.has(posix.basename(filePath)) ||
    isGeneratedDirPath(filePath)
  );
}
